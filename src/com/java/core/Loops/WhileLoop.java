package com.java.core.Loops;

public class WhileLoop {

	public static void main(String[] args) {

	/* When we write a code with the help of 
	  WHILE LOOP the outer execution and inner execution 
	  will be same sequence like,
	  *1-: Declare + initialization.
	  *2-: condition/Statement.
	  *3-: Print inner body of while loop.
	  *4-:Increment/Decrement. */
		
//1-:initialization
		int a =1;
//condition/Statement,given in parenthesis
		while(a<=5) {
//print			
			System.out.println(a);
//Increment/Decrement			
			a++;
		}
	}

}
